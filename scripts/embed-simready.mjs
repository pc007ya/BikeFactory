import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const dir=new URL('../assets/simready/',import.meta.url);
const assets=[];
for(const [id,label] of [['barrier_fence_metal_a02','金屬護欄'],['box_corrugated_brown_b08','瓦楞紙箱']]){
 const bytes=await fs.readFile(new URL(id+'.glb',dir));
 assets.push({id,label,sha256:createHash('sha256').update(bytes).digest('hex'),base64:bytes.toString('base64')});
}
await fs.writeFile(new URL('embedded.js',dir),'// Generated by scripts/embed-simready.mjs; original NVIDIA asset attribution is in ATTRIBUTION.md.\nexport const SIMREADY_ASSETS='+JSON.stringify(assets)+';\n');
